<?php
/** File-only installer operations. No PrestaShop or database access. */
class WatchysDevFiles
{
    public static function entries($root)
    {
        if(is_link($root)) {throw new RuntimeException('Dossier module symbolique refusé.');}
        if(file_exists($root)&&!is_dir($root)){throw new RuntimeException('Chemin module occupé par un fichier.');}
        if(!is_dir($root)) {return [];}
        $files=[];
        foreach(new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root,FilesystemIterator::SKIP_DOTS)) as $f) {
            if($f->isLink()) {throw new RuntimeException('Lien symbolique dans le module refusé.');}
            if($f->isFile()) {$files[substr($f->getPathname(),strlen($root)+1)]=hash_file('sha256',$f->getPathname());}
        }
        ksort($files);return $files;
    }
    public static function checkExisting($root,$current,$legacy,$assets)
    {
        $files=self::entries($root);$assetHashes=[];foreach($assets as $a){$assetHashes['views/img/'.$a['target']]=$a['sha256'];}
        foreach($files as $file=>$sha) {
            if($file==='config.xml' && filesize($root.'/'.$file)<65536) {continue;} // Generated by PrestaShop; backed up, never executed.
            $allowed=array_filter([$current[$file]??null,$legacy[$file]??null,$assetHashes[$file]??null]);
            if(!in_array($sha,$allowed,true)) {throw new RuntimeException('Fichier existant non reconnu : '.$file.'. Aucune écriture autorisée.');}
        }
        return $files;
    }
    public static function copy($source,$target,$sha)
    {
        if(!is_file($source)||is_link($source)||hash_file('sha256',$source)!==$sha) {throw new RuntimeException('Source absente ou modifiée : '.basename($source));}
        if(file_exists($target)||is_link($target)) {throw new RuntimeException('Écrasement de fichier refusé.');}
        $dir=dirname($target);
        if(!is_dir($dir)) { $pending=[];$walk=$dir;while(!is_dir($walk)) {$pending[]=$walk;$walk=dirname($walk);}foreach(array_reverse($pending) as $p){if(!mkdir($p,0755)||!chmod($p,0755)){throw new RuntimeException('Dossier non créé.');}} }
        $in=fopen($source,'rb');$out=fopen($target,'xb');if(!$in||!$out) {throw new RuntimeException('Copie exclusive impossible.');}
        try{$ok=stream_copy_to_stream($in,$out);}finally{fclose($in);fclose($out);}
        if($ok===false||!chmod($target,0644)||hash_file('sha256',$target)!==$sha) {throw new RuntimeException('Copie non validée.');}
    }
    public static function publish($stage,$target,$backup)
    {
        $hadTarget=is_dir($target);
        if(file_exists($backup)||is_link($target)||is_link($stage)) {throw new RuntimeException('Chemin de publication non autorisé.');}
        if($hadTarget&&!rename($target,$backup)) {throw new RuntimeException('Sauvegarde du module existant impossible ; module conservé.');}
        if(!rename($stage,$target)) {
            if($hadTarget&&!rename($backup,$target)){throw new RuntimeException('Publication échouée ; restauration automatique non confirmée. Sauvegarde : '.$backup);}
            throw new RuntimeException('Publication échouée ; ancien module rétabli.');
        }
    }
    public static function saveJournal($path,$data)
    {
        if(is_link($path)||is_link($path.'.tmp')) {throw new RuntimeException('Journal symbolique refusé.');}
        $bytes=json_encode($data,JSON_UNESCAPED_UNICODE|JSON_THROW_ON_ERROR);$tmp=$path.'.tmp';
        if(file_put_contents($tmp,$bytes,LOCK_EX)!==strlen($bytes)||!chmod($tmp,0600)||!rename($tmp,$path)) {throw new RuntimeException('Journal non enregistré.');}
    }
}
